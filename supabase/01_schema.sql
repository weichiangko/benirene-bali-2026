create table if not exists days(
  id bigint generated by default as identity primary key,
  position double precision not null default 0,
  date text not null default '',
  title text not null default '',
  area text not null default '',
  note text not null default '',
  breakfast text not null default '',
  map_note text not null default '',
  route_geometry jsonb,
  route_sig text,
  updated_at timestamptz not null default now()
);
create table if not exists items(
  id text primary key default ('i-'||substr(md5(random()::text),1,10)),
  day_id bigint not null references days(id) on delete cascade,
  position double precision not null default 0,
  time text not null default '',
  title text not null default '',
  type text not null default '',
  note text not null default '',
  reserve text not null default '',
  book_url text not null default '',
  map_url text not null default '',
  food text[] not null default '{}',
  booking text[] not null default '{}',
  extra text[] not null default '{}',
  rain text[] not null default '{}',
  photos jsonb not null default '[]',
  lat double precision,
  lng double precision,
  point_name text not null default '',
  coord_key text not null default '',
  updated_at timestamptz not null default now()
);
create index if not exists items_day on items(day_id, position);
create table if not exists checks(
  id text primary key default ('c-'||substr(md5(random()::text),1,10)),
  position double precision not null default 0,
  title text not null default '',
  detail text not null default '',
  done boolean not null default false,
  updated_at timestamptz not null default now()
);
create table if not exists notes(
  id text primary key default ('n-'||substr(md5(random()::text),1,10)),
  position double precision not null default 0,
  title text not null default '',
  paragraphs text[] not null default '{}',
  updated_at timestamptz not null default now()
);
create table if not exists history(
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  tbl text not null,
  row_id text not null,
  op text not null,
  old jsonb,
  new jsonb
);
create index if not exists history_at on history(at desc);

create or replace function touch_updated() returns trigger language plpgsql as $$
begin new.updated_at := now(); return new; end $$;

create or replace function log_change() returns trigger language plpgsql security definer set search_path = public as $$
declare o jsonb; n jsonb;
begin
  if tg_op <> 'INSERT' then o := to_jsonb(old) - 'route_geometry'; end if;
  if tg_op <> 'DELETE' then n := to_jsonb(new) - 'route_geometry'; end if;
  if tg_op = 'UPDATE' and (o - 'updated_at') = (n - 'updated_at') then return new; end if;
  insert into history(tbl,row_id,op,old,new) values (tg_table_name, coalesce(n->>'id', o->>'id'), tg_op, o, n);
  return coalesce(new, old);
end $$;

do $$ declare t text; begin
  foreach t in array array['days','items','checks','notes'] loop
    execute format('drop trigger if exists %I_touch on %I', t, t);
    execute format('create trigger %I_touch before update on %I for each row execute function touch_updated()', t, t);
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists open_all on %I', t);
    execute format('create policy open_all on %I for all to anon, authenticated using (true) with check (true)', t);
  end loop;
end $$;
alter table history enable row level security;
drop policy if exists read_all on history;
create policy read_all on history for select to anon, authenticated using (true);
grant select, insert, update, delete on days, items, checks, notes to anon, authenticated;
grant select on history to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;
